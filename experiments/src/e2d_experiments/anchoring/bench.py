"""Proof size and Merkle tree build time against tree size, using the shared e2d-core ledger.

The build time is the in-memory part of a checkpoint (leaf hashes to root) on the machine that runs
the script; reading the events from the database is not included. The machine is recorded.
"""

import os
import platform
import statistics
import time
import uuid
from datetime import UTC, datetime
from typing import Any

import polars as pl

from e2d_core.ledger.hashchain import payload_hash
from e2d_core.ledger.merkle import MerkleTree, leaf_hash
from e2d_core.ledger.sth import TreeHead, derive_clinic_key, key_id, public_key_bytes, sign

HASH_BYTES = 32
SIGNATURE_BYTES = 64


def sth_bytes(tree_size: int) -> int:
    """Size of a signed tree head as published: canonical JSON plus the Ed25519 signature."""
    head = TreeHead(
        clinic_id=str(uuid.UUID(int=0)),
        tree_size=tree_size,
        root_hex="00" * HASH_BYTES,
        prev_root_hex="00" * HASH_BYTES,
        timestamp=int(datetime(2026, 1, 1, tzinfo=UTC).timestamp() * 1000),
        key_id="0" * 16,
    )
    return len(head.signing_bytes()) + SIGNATURE_BYTES


def leaves(n: int) -> list[bytes]:
    return [leaf_hash(i.to_bytes(8, "big")) for i in range(n)]


def proof_sizes(sizes: list[int]) -> pl.DataFrame:
    rows = []
    for n in sizes:
        tree = MerkleTree(leaves(n))
        longest = max(len(tree.inclusion_proof(i)) for i in (0, n // 2, n - 1))
        consistency = len(tree.consistency_proof(max(1, n // 2))) if n > 1 else 0
        rows.append(
            {
                "tree_size": n,
                "inclusion_hashes": longest,
                "inclusion_bytes": longest * HASH_BYTES,
                "consistency_bytes": consistency * HASH_BYTES,
                "sth_bytes": sth_bytes(n),
            }
        )
    return pl.DataFrame(rows)


def build_times(sizes: list[int], repeats: int) -> pl.DataFrame:
    rows = []
    for n in sizes:
        hashes = leaves(n)
        times = []
        for _ in range(repeats):
            start = time.perf_counter()
            MerkleTree(hashes).root()
            times.append(time.perf_counter() - start)
        rows.append(
            {
                "tree_size": n,
                "repeats": repeats,
                "median_s": statistics.median(times),
                "max_s": max(times),
            }
        )
    return pl.DataFrame(rows)


BENCH_SEED = b"healthsaathi-receipt-bench-seed-01"
BENCH_CLINIC = uuid.UUID("01920000-0000-7000-8000-0000000bec01")


def bench_payload(i: int) -> dict[str, Any]:
    """Shaped like the audit payload the API writes for an access (synthetic ids only)."""
    return {
        "type": "access",
        "access_event_id": f"01920000-0000-7000-8000-{i:012x}",
        "at": "2026-11-01T09:30:00+00:00",
        "user_id": "01920000-0000-7000-8000-0000000000d1",
        "role": "doctor",
        "patient_id": "01920000-0000-7000-8000-0000000000e1",
        "resource": "chart",
        "action": "view",
        "decision": "allow",
        "policy_version": "1",
        "template": "T2_QUEUE_TOKEN",
        "strength": 0.731058,
    }


def bench_receipt(tree_size: int) -> dict[str, Any]:
    """A valid receipt, in the API's format, for the first leaf of a tree of `tree_size` leaves.
    The first leaf has the longest proof (ceil(log2 n) hashes); the last leaf of a tree whose size
    is not a power of two sits in a small right subtree and has a shorter one. Signed with a fixed
    public bench key."""
    key = derive_clinic_key(BENCH_SEED, BENCH_CLINIC)
    public = public_key_bytes(key)
    index = 0
    payload = bench_payload(index)
    digest = payload_hash(payload)
    hashes = [leaf_hash(digest), *leaves(tree_size - 1)]
    tree = MerkleTree(hashes)
    head = TreeHead(
        clinic_id=str(BENCH_CLINIC),
        tree_size=tree_size,
        root_hex=tree.root().hex(),
        prev_root_hex=None,
        timestamp=int(datetime(2026, 11, 1, tzinfo=UTC).timestamp() * 1000),
        key_id=key_id(public),
    )
    return {
        "version": 1,
        "clinic_id": str(BENCH_CLINIC),
        "clinic_id_bytes32": "0x" + (BENCH_CLINIC.bytes + bytes(16)).hex(),
        "public_key": public.hex(),
        "audit_seq": index + 1,
        "payload": payload,
        "payload_hash": digest.hex(),
        "leaf_hash": leaf_hash(digest).hex(),
        "leaf_index": index,
        "proof": [h.hex() for h in tree.inclusion_proof(index)],
        "sth": head.to_json(),
        "signature": sign(head, key).hex(),
        "anchors": [],
    }


def bench_file(sizes: list[int], probe: dict[str, str] | None) -> dict[str, Any]:
    """The receipt timing page's input (apps/web/public/bench/receipts.json). `probe` names a
    live clinic and anchor transaction, so the page makes the same chain reads as a real check."""
    return {
        "note": "Generated by python -m e2d_experiments.anchoring bench-receipts. Do not edit.",
        "receipts": [{"tree_size": n, "receipt": bench_receipt(n)} for n in sizes],
        "chain_probe": probe,
    }


def machine() -> str:
    system = f"{platform.system()} {platform.machine()}"
    return f"{system}, {os.cpu_count()} CPUs, Python {platform.python_version()}"
