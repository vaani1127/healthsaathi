"""Pre-registered hypothesis report (H1 to H4) from finished experiment runs.

    uv run python -m e2d_experiments.report experiments/outputs/v1 --export paper/tables

Reads `<root>/none/results.parquet` (main run) and `<root>/no_forgery/results.parquet` (for H4).
"""

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import polars as pl

from e2d_experiments import stats

ROW_END = " \\\\"


def report(root: Path) -> dict[str, Any]:
    main = pl.read_parquet(root / "none" / "results.parquet")
    h2 = stats.hypothesis_tests(main)
    temporal5 = h2.filter((pl.col("split") == "temporal") & (pl.col("budget") == 5))
    baseline = temporal5["best_baseline"][0] if temporal5.height else stats.RAW_BASELINES[0]
    out: dict[str, Any] = {
        "h1": stats.h1(main),
        "h2": h2.to_dicts(),
        "h3": {"baseline": baseline, **stats.h3(main, baseline)},
    }
    no_forgery = root / "no_forgery" / "results.parquet"
    if no_forgery.exists():
        out["h4"] = stats.h4(main, pl.read_parquet(no_forgery)).to_dicts()
    return out


def hypotheses_tex(result: dict[str, Any]) -> str:
    h1, h3 = result["h1"], result["h3"]

    def interval(name: str) -> str:
        return f"{h1[name + '_mean']:.3f} [{h1[name + '_low']:.3f}, {h1[name + '_high']:.3f}]"

    rows = [
        f"H1 coverage & {interval('coverage')}{ROW_END}",
        f"H1 false explanation rate & {interval('false_explanation_rate')}{ROW_END}",
        f"H3 gain difference vs {h3['baseline']} & "
        f"{h3['mean_difference']:.3f} (p = {h3['p']:.4f}){ROW_END}",
    ]
    for row in result.get("h4", []):
        rows.append(
            f"H4 type 10 recall, {row['split']} & {row['with_forgery']:.3f} vs "
            f"{row['without_forgery']:.3f} (p Holm = {row['p_holm']:.4f}){ROW_END}"
        )
    lines = [
        "% Generated by e2d_experiments.report. Do not edit by hand.",
        "\\begin{table}[t]",
        "\\centering",
        "\\small",
        "\\caption{Pre-registered hypotheses H1, H3 and H4 (H2 is in Table~\\ref{tab:tests}).}",
        "\\label{tab:hypotheses}",
        "\\begin{tabular}{lr}",
        "\\toprule",
        *rows,
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="Hypothesis report for E2D experiments.")
    parser.add_argument("root", type=Path, help="experiments/outputs/<data name>")
    parser.add_argument("--export", type=Path, help="also write hypotheses.tex here")
    args = parser.parse_args(argv)
    result = report(args.root)
    text = json.dumps(result, indent=2, default=str)
    (args.root / "hypotheses.json").write_text(text, encoding="utf-8")
    print(text)
    if args.export:
        args.export.mkdir(parents=True, exist_ok=True)
        (args.export / "hypotheses.tex").write_text(hypotheses_tex(result), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
