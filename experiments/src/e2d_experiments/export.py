"""Write result tables as LaTeX and figures as PDF. Every number in them comes from the results
files of a run; nothing is typed by hand."""

from pathlib import Path

import polars as pl

from e2d_experiments.stats import BASELINES

METHOD_NAMES = {
    "b0_rules": "B0 rules",
    "b1_iforest": "B1 IForest",
    "b2_iforest_role": "B2 IForest per role",
    "b3_vae": "B3 sequence VAE",
    "b4_coaccess": "B4 co-access CF",
    "b5_explanation_only": "B5 explanation only",
    "e2d": "E2D",
    "e2d_ecod": "E2D (ECOD)",
    "e2d_copod": "E2D (COPOD)",
    "upper_lightgbm": "Upper bound (LightGBM)",
}
SPLITS = ("temporal", "clinic", "attack", "user")


def _cell(mean: float, low: float, high: float) -> str:
    if mean != mean:  # NaN
        return "--"
    return f"{mean:.3f} [{low:.3f}, {high:.3f}]"


def _tabular(header: list[str], rows: list[list[str]], caption: str, label: str) -> str:
    cols = "l" + "r" * (len(header) - 1)
    lines = [
        "% Generated by e2d_experiments.export. Do not edit by hand.",
        "\\begin{table}[t]",
        "\\centering",
        "\\small",
        f"\\caption{{{caption}}}",
        f"\\label{{{label}}}",
        f"\\begin{{tabular}}{{{cols}}}",
        "\\toprule",
        " & ".join(header) + " \\\\",
        "\\midrule",
        *(" & ".join(r) + " \\\\" for r in rows),
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
    ]
    return "\n".join(lines) + "\n"


def main_table(
    summary: pl.DataFrame, budget: int = 5, metric: str = "recall", cluster: bool = False
) -> str:
    """Mean with the seed-bootstrap interval, or with the clinic cluster interval."""
    cells = summary.filter(
        (pl.col("metric") == metric)
        & (pl.col("budget") == budget)
        & (pl.col("ablation") == "none")
        & pl.col("group").is_null()
    )
    present = [s for s in SPLITS if s in set(cells["split"])]
    low, high = ("cluster_low", "cluster_high") if cluster else ("ci_low", "ci_high")
    rows = []
    for method in METHOD_NAMES:
        mine = cells.filter(pl.col("method") == method)
        if mine.is_empty():
            continue
        row = [METHOD_NAMES[method]]
        for split in present:
            hit = mine.filter(pl.col("split") == split)
            if hit.height and hit[low][0] is not None:
                row.append(_cell(*hit.select("mean", low, high).row(0)))
            else:
                row.append("--")
        rows.append(row)
    kind = "cluster bootstrap over test clinics" if cluster else "bootstrap over seeds"
    return _tabular(
        ["Method", *present],
        rows,
        f"{metric.replace('_', ' ').capitalize()} at B = {budget} alerts per clinic-day "
        f"(mean and 95\\% {kind}).",
        f"tab:{metric}-at-{budget}" + ("-cluster" if cluster else ""),
    )


def tests_table(tests: pl.DataFrame) -> str:
    rows = [
        [
            str(r["split"]) + (" (primary)" if r["primary"] else ""),
            str(r["budget"]),
            METHOD_NAMES.get(r["best_baseline"], r["best_baseline"]),
            f"{r['e2d_mean']:.3f}",
            f"{r['baseline_mean']:.3f}",
            f"{r['p_adjusted']:.4f}",
            f"{r['effect']:.2f}",
            str(r["zeros_dropped"]),
        ]
        for r in tests.sort(
            ["primary", "split", "budget"], descending=[True, False, False]
        ).iter_rows(named=True)
    ]
    return _tabular(
        ["Split", "B", "Best raw baseline", "E2D", "Baseline", "p", "r", "Zeros"],
        rows,
        "H2: E2D against the best raw-feature baseline, one-sided paired Wilcoxon over seeds. The "
        "primary test (temporal, B = 5) is not corrected; the others are Holm-corrected together. "
        "r is the matched-pairs rank-biserial effect size; Zeros counts dropped zero differences.",
        "tab:tests",
    )


def explanation_table(summary: pl.DataFrame) -> str:
    cells = summary.filter(pl.col("metric").is_in(["coverage", "false_explanation_rate"]))
    rows = []
    for split in SPLITS:
        part = cells.filter(pl.col("split") == split)
        if part.is_empty():
            continue
        values = {r["metric"]: r for r in part.iter_rows(named=True)}
        rows.append(
            [split]
            + [
                _cell(values[m]["mean"], values[m]["ci_low"], values[m]["ci_high"])
                if m in values
                else "--"
                for m in ("coverage", "false_explanation_rate")
            ]
        )
    return _tabular(
        ["Split", "Coverage", "False explanation rate"],
        rows,
        "Explanation coverage of benign accesses and false-explanation rate of non-forging "
        "attacks on the test part of each split.",
        "tab:coverage",
    )


def write_tables(summary: pl.DataFrame, tests: pl.DataFrame, out: Path) -> list[Path]:
    out.mkdir(parents=True, exist_ok=True)
    written = []
    budgets = sorted(summary.filter(pl.col("metric") == "recall")["budget"].unique().to_list())
    for b in budgets:
        for metric in ("recall", "precision", "alerts_raised"):
            path = out / f"{metric}_at_{b}.tex"
            path.write_text(main_table(summary, b, metric), encoding="utf-8")
            written.append(path)
        for metric in ("recall", "precision"):
            path = out / f"{metric}_at_{b}_cluster.tex"
            path.write_text(main_table(summary, b, metric, cluster=True), encoding="utf-8")
            written.append(path)
    path = out / "pr_auc.tex"
    path.write_text(main_table(summary, budgets[0] if budgets else 5, "pr_auc"), encoding="utf-8")
    written.append(path)
    if tests.height:
        path = out / "tests.tex"
        path.write_text(tests_table(tests), encoding="utf-8")
        written.append(path)
    path = out / "coverage.tex"
    path.write_text(explanation_table(summary), encoding="utf-8")
    written.append(path)
    return written


def write_figures(summary: pl.DataFrame, out: Path) -> list[Path]:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    out.mkdir(parents=True, exist_ok=True)
    written = []
    recall = summary.filter(
        (pl.col("metric") == "recall") & (pl.col("ablation") == "none") & pl.col("group").is_null()
    )
    for split in SPLITS:
        part = recall.filter(pl.col("split") == split)
        if part.is_empty():
            continue
        fig, ax = plt.subplots(figsize=(5, 3))
        for method in ("e2d", *BASELINES):
            line = part.filter(pl.col("method") == method).sort("budget")
            if line.is_empty():
                continue
            ax.errorbar(
                line["budget"].to_list(),
                line["mean"].to_list(),
                yerr=[
                    (line["mean"] - line["ci_low"]).to_list(),
                    (line["ci_high"] - line["mean"]).to_list(),
                ],
                label=METHOD_NAMES[method],
                marker="o",
                capsize=2,
            )
        ax.set_xlabel("Alerts per clinic-day (B)")
        ax.set_ylabel("Recall")
        ax.set_title(f"{split} split")
        ax.legend(fontsize=6)
        fig.tight_layout()
        path = out / f"recall_by_budget_{split}.pdf"
        fig.savefig(path)
        plt.close(fig)
        written.append(path)
    return written
