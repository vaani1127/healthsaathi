"""A 4-validator Besu QBFT network on this computer, for the anchoring study (SPEC 8, P16).

    python -m hs_demo.besu up              # make besu-up: genesis, nodes, contracts
    python -m hs_demo.besu bench [N]       # make besu-bench: register a clinic, send N anchors
    python -m hs_demo.besu down            # make besu-down: stop and delete the network

Everything it generates (validator keys, test accounts, chain data) stays in `.demo/besu`, which
is gitignored; the accounts only hold this network's test ether. The bench sends anchors with the
app's own EvmAnchor client and signed tree heads from e2d-core, and writes `checkpoints.parquet`
and `enriched.parquet` in the anchoring study's format (backend "besu") to
`experiments/results/anchoring/besu`.
"""

import asyncio
import json
import os
import random
import shutil
import subprocess
import sys
import time
import urllib.request
import uuid
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import polars as pl
from eth_account import Account

from app.anchor.evm import ZERO32, EvmAnchor
from app.scripts.register_clinic import registration
from e2d_core.ledger.merkle import MerkleTree, leaf_hash
from e2d_core.ledger.sth import TreeHead, derive_clinic_key, key_id, public_key_bytes
from hs_demo.native import CONTRACTS, ROOT, tool

STATE = ROOT / ".demo" / "besu"
RESULTS = ROOT / "experiments" / "results" / "anchoring" / "besu"
IMAGE = os.environ.get("BESU_IMAGE", "hyperledger/besu:26.10.2")
CHAIN_ID = 1337
RPC = "http://127.0.0.1:8545"
SUBNET = "172.16.240"
NODES = 4
BLOCK_PERIOD_SECONDS = 2
# Fixed, public bench seed: these clinic keys sign only bench tree heads.
BENCH_SEED = b"healthsaathi-besu-bench-seed-0001"
BENCH_CLINIC = uuid.UUID("01920000-0000-7000-8000-0000000be5a0")
QBFT_MIX_HASH = "0x63746963616c2062797a616e74696e65206661756c7420746f6c6572616e6365"


def say(message: str) -> None:
    print(f"[besu] {message}", flush=True)


def run(args: list[str], cwd: Path = ROOT, env: dict[str, str] | None = None) -> None:
    subprocess.run(args, cwd=cwd, env=env or dict(os.environ), check=True)  # noqa: S603


def docker_path(path: Path) -> str:
    """Docker Desktop on Windows takes forward slashes."""
    return path.resolve().as_posix()


def genesis_config(accounts: list[str]) -> dict[str, Any]:
    """Input for `besu operator generate-blockchain-config`. Cancun, because the contracts are
    compiled for it (contracts/foundry.toml); zero base fee, so the test accounts never run dry."""
    return {
        "genesis": {
            "config": {
                "chainId": CHAIN_ID,
                "berlinBlock": 0,
                "londonBlock": 0,
                "shanghaiTime": 0,
                "cancunTime": 0,
                "zeroBaseFee": True,
                "qbft": {
                    "blockperiodseconds": BLOCK_PERIOD_SECONDS,
                    "epochlength": 30000,
                    "requesttimeoutseconds": 4,
                },
            },
            "nonce": "0x0",
            "timestamp": "0x0",
            "gasLimit": "0x1fffffffffffff",
            "difficulty": "0x1",
            "mixHash": QBFT_MIX_HASH,
            "coinbase": "0x0000000000000000000000000000000000000000",
            "alloc": {a.removeprefix("0x"): {"balance": hex(10**24)} for a in accounts},
        },
        "blockchain": {"nodes": {"generate": True, "count": NODES}},
    }


def compose_file(enode_key: str) -> str:
    bootnode = f"enode://{enode_key}@{SUBNET}.11:30303"
    services = []
    for i in range(1, NODES + 1):
        args = [
            "--genesis-file=/config/genesis.json",
            "--data-path=/data",
            "--node-private-key-file=/data/key",
            f"--p2p-host={SUBNET}.{10 + i}",
            "--rpc-http-enabled",
            "--rpc-http-host=0.0.0.0",
            "--rpc-http-api=ETH,NET,QBFT,WEB3",
            "--host-allowlist=*",
            "--rpc-http-cors-origins=all",
            "--min-gas-price=0",
        ]
        if i > 1:
            args.append(f"--bootnodes={bootnode}")
        ports = '\n    ports: ["8545:8545"]' if i == 1 else ""
        services.append(
            f"""  node{i}:
    image: {IMAGE}
    command: {json.dumps(args)}
    environment:
      JAVA_OPTS: "-Xmx512m"
    volumes:
      - ./network/genesis.json:/config/genesis.json:ro
      - ./node{i}:/data
    networks:
      besu:
        ipv4_address: {SUBNET}.{10 + i}{ports}
"""
        )
    return (
        "# Generated by hs_demo.besu. Local test network only.\nname: healthsaathi-besu\n"
        "services:\n"
        + "".join(services)
        + f"networks:\n  besu:\n    ipam:\n      config:\n        - subnet: {SUBNET}.0/24\n"
    )


def rpc(method: str, params: list[Any] | None = None) -> Any:
    body = json.dumps({"jsonrpc": "2.0", "id": 1, "method": method, "params": params or []})
    req = urllib.request.Request(RPC, body.encode(), {"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=5) as resp:  # noqa: S310 - local node
        return json.loads(resp.read())["result"]


def wait_for_blocks(count: int, seconds: int = 180) -> int:
    deadline = time.time() + seconds
    while time.time() < deadline:
        try:
            height = int(rpc("eth_blockNumber"), 16)
            if height >= count:
                return height
        except OSError:
            pass
        time.sleep(2)
    raise SystemExit("the Besu network did not produce blocks; see docker compose logs")


def compose(*args: str) -> None:
    run([tool("docker"), "compose", "-f", str(STATE / "docker-compose.yml"), *args])


def up() -> None:
    if (STATE / "docker-compose.yml").exists():
        compose("up", "-d")
        say(f"network running, block {wait_for_blocks(1)}")
        return
    STATE.mkdir(parents=True, exist_ok=True)
    wallets = [Account.create() for _ in range(4)]
    accounts = {
        "deployer": {"address": wallets[0].address, "key": wallets[0].key.hex()},
        "admins": [{"address": w.address, "key": w.key.hex()} for w in wallets[1:]],
    }
    (STATE / "accounts.json").write_text(json.dumps(accounts, indent=2), encoding="utf-8")
    config = genesis_config([w.address for w in wallets])
    (STATE / "qbft.json").write_text(json.dumps(config, indent=2), encoding="utf-8")
    say("generating the genesis and validator keys")
    shutil.rmtree(STATE / "network", ignore_errors=True)
    # Besu 26.10 writes the files and then exits with "Output directory already exists", so the
    # files are checked instead of the exit status.
    subprocess.run(  # noqa: S603
        [
            tool("docker"), "run", "--rm", "-v", f"{docker_path(STATE)}:/work", IMAGE,
            "operator", "generate-blockchain-config", "--config-file=/work/qbft.json",
            "--to=/work/network", "--private-key-file-name=key",
        ],
        check=False,
    )  # fmt: skip
    keys = sorted(p for p in (STATE / "network" / "keys").iterdir() if p.is_dir())
    if not (STATE / "network" / "genesis.json").exists() or len(keys) != NODES:
        raise SystemExit("Besu did not write the genesis and validator keys")
    for i, folder in enumerate(keys, start=1):
        node = STATE / f"node{i}"
        node.mkdir(exist_ok=True)
        (node / "key").write_bytes((folder / "key").read_bytes())
    enode = (keys[0] / "key.pub").read_text(encoding="utf-8").strip().removeprefix("0x")
    (STATE / "docker-compose.yml").write_text(compose_file(enode), encoding="utf-8")
    compose("up", "-d")
    say(f"network running, block {wait_for_blocks(2)}")
    deploy(accounts)


def deploy(accounts: dict[str, Any]) -> None:
    env = {
        **os.environ,
        "DEPLOY_NETWORK": "besu",
        **{f"REGISTRY_ADMIN_{i}": a["address"] for i, a in enumerate(accounts["admins"], 1)},
    }
    key = "0x" + accounts["deployer"]["key"].removeprefix("0x")
    script = ["script", "script/Deploy.s.sol", "--rpc-url", RPC, "--broadcast", "--private-key"]
    run([tool("forge"), *script, key], CONTRACTS, env)
    say("contracts deployed")


def deployment() -> dict[str, Any]:
    data: dict[str, Any] = json.loads(
        (CONTRACTS / "deployments" / "besu.json").read_text(encoding="utf-8")
    )
    return data


def as_key(value: str) -> str:
    return "0x" + value.removeprefix("0x")


async def bench(anchors: int, seed: int = 7) -> Path:
    accounts = json.loads((STATE / "accounts.json").read_text(encoding="utf-8"))
    contracts = deployment()
    poster = as_key(accounts["deployer"]["key"])
    evm = EvmAnchor(RPC, contracts["AuditAnchor"], poster, contracts["ClinicRegistry"])
    signing_key = derive_clinic_key(BENCH_SEED, BENCH_CLINIC)
    public = public_key_bytes(signing_key)
    rng = random.Random(seed)  # noqa: S311 - tree growth, not security
    checkpoints: list[dict[str, Any]] = []
    receipts: list[dict[str, Any]] = []
    try:
        size, root = await evm.latest(BENCH_CLINIC)
        if not any(await evm.signer_key_hash(BENCH_CLINIC) or b""):
            reg = registration(BENCH_CLINIC, accounts["deployer"]["address"])
            for admin in accounts["admins"][:2]:
                await evm.wait(
                    await evm.confirm_registration(
                        as_key(admin["key"]),
                        BENCH_CLINIC,
                        bytes.fromhex(reg.key_hash[2:]),
                        reg.poster,
                    )
                )
            say("bench clinic registered")
        leaves = [leaf_hash(i.to_bytes(8, "big")) for i in range(size)]
        prev = root if size else ZERO32
        for n in range(anchors):
            leaves += [leaf_hash(rng.randbytes(32)) for _ in range(rng.randint(5, 60))]
            tree = MerkleTree(leaves)
            signed_at = datetime.now(UTC)
            head = TreeHead(
                clinic_id=str(BENCH_CLINIC),
                tree_size=tree.size,
                root_hex=tree.root().hex(),
                prev_root_hex=prev.hex() if any(prev) else None,
                timestamp=int(signed_at.timestamp() * 1000),
                key_id=key_id(public),
            )
            submitted = datetime.now(UTC)
            tx = await evm.send_anchor(BENCH_CLINIC, tree.size, tree.root(), prev, head.digest())
            mined = await evm.wait(tx)
            confirmed = datetime.now(UTC)
            receipt = await evm.w3.eth.get_transaction_receipt(tx)  # type: ignore[arg-type]
            block = await evm.w3.eth.get_block(receipt["blockNumber"])
            checkpoint_id = str(uuid.uuid4())
            checkpoints.append(
                {
                    "checkpoint_id": checkpoint_id,
                    "clinic_id": str(BENCH_CLINIC),
                    "tree_size": tree.size,
                    "signed_at": signed_at,
                }
            )
            receipts.append(
                {
                    "checkpoint_id": checkpoint_id,
                    "clinic_id": str(BENCH_CLINIC),
                    "backend": "besu",
                    "status": "confirmed" if mined.succeeded else "failed",
                    "tx_ref": tx,
                    "block_ref": str(mined.block_number),
                    "submitted_at": submitted,
                    "confirmed_at": confirmed,
                    "final_at": datetime.fromtimestamp(int(block["timestamp"]), UTC),
                    "gas_used": int(receipt["gasUsed"]),
                    "gas_price_wei": int(receipt["effectiveGasPrice"]),
                }
            )
            prev = tree.root()
            if (n + 1) % 25 == 0:
                say(f"{n + 1} of {anchors} anchors")
    finally:
        await evm.close()
    return write_results(checkpoints, receipts)


def write_results(checkpoints: list[dict[str, Any]], receipts: list[dict[str, Any]]) -> Path:
    ts = pl.Datetime("us", "UTC")
    RESULTS.mkdir(parents=True, exist_ok=True)
    pl.DataFrame(
        checkpoints,
        schema={
            "checkpoint_id": pl.String,
            "clinic_id": pl.String,
            "tree_size": pl.Int64,
            "signed_at": ts,
        },
        orient="row",
    ).write_parquet(RESULTS / "checkpoints.parquet")
    pl.DataFrame(
        receipts,
        schema={
            "checkpoint_id": pl.String,
            "clinic_id": pl.String,
            "backend": pl.String,
            "status": pl.String,
            "tx_ref": pl.String,
            "block_ref": pl.String,
            "submitted_at": ts,
            "confirmed_at": ts,
            "final_at": ts,
            "gas_used": pl.Int64,
            "gas_price_wei": pl.Int64,
        },
        orient="row",
    ).write_parquet(RESULTS / "enriched.parquet")
    (RESULTS / "network.txt").write_text(
        f"image={IMAGE}\nvalidators={NODES}\nblock_period_seconds={BLOCK_PERIOD_SECONDS}\n"
        f"anchors={len(receipts)}\nrun_at={datetime.now(UTC).isoformat()}\n",
        encoding="utf-8",
    )
    return RESULTS


def down() -> None:
    if (STATE / "docker-compose.yml").exists():
        compose("down", "-v")
    say("network stopped; delete .demo/besu to start from a new genesis")


def main(argv: list[str]) -> int:
    command = argv[0] if argv else ""
    if command == "up":
        up()
    elif command == "bench":
        out = asyncio.run(bench(int(argv[1]) if len(argv) > 1 else 200))
        say(f"results in {out}")
    elif command == "down":
        down()
    else:
        raise SystemExit(__doc__)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
